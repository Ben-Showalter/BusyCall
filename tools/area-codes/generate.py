#!/usr/bin/env python3
"""
Builds BusyCall's "where is this number from" data (AGENTS: generated, never hand-edited).

Inputs (download them, then pass the paths):
  1. libphonenumber's geocoding file resources/geocoding/en/1.txt (Apache-2.0)
     https://github.com/google/libphonenumber
  2. Natural Earth 1:50m admin-1 states/provinces (public domain)
     ne_50m_admin_1_states_provinces_lakes.geojson

Outputs (into app/src/main/assets/):
  bc_area_codes.csv  area code,region   region = state/province codes ("OH", "NS/PE")
                                        or a country/territory name ("Jamaica")
  bc_regions.csv     code,name          the US states and Canadian provinces
  bc_map.bin         the region shapes, simplified (see ui/PlaceMapView for the format)

Usage: python3 -I generate.py 1.txt ne_50m_admin_1_states_provinces_lakes.geojson ../../app/src/main/assets
"""
import json
import math
import os
import re
import struct
import sys
from collections import Counter

# NANP area codes outside the US and Canada (they have no state or province).
OTHER = {
    "242": "Bahamas", "246": "Barbados", "264": "Anguilla", "268": "Antigua and Barbuda",
    "284": "British Virgin Islands", "340": "US Virgin Islands", "345": "Cayman Islands",
    "441": "Bermuda", "473": "Grenada", "649": "Turks and Caicos", "658": "Jamaica",
    "876": "Jamaica", "664": "Montserrat", "670": "Northern Mariana Islands", "671": "Guam",
    "684": "American Samoa", "721": "Sint Maarten", "758": "Saint Lucia", "767": "Dominica",
    "784": "Saint Vincent and the Grenadines", "787": "Puerto Rico", "939": "Puerto Rico",
    "809": "Dominican Republic", "829": "Dominican Republic", "849": "Dominican Republic",
    "868": "Trinidad and Tobago", "869": "Saint Kitts and Nevis",
}

# libphonenumber's names that aren't a plain state/province name.
SPECIAL = {
    "Washington D.C.": "DC", "Washington State": "WA", "British Colombia": "BC",
    "Quebec": "QC", "Nova Scotia/Prince Edward Island": "NS/PE",
    "Northwest Territories/Nunavut/Yukon": "NT/NU/YT",
}


def main(geo_path, ne_path, out_dir):
    features = [f for f in json.load(open(ne_path, encoding="utf-8"))["features"]
                if f["properties"].get("adm0_a3") in ("USA", "CAN")]
    names = {f["properties"]["postal"]: f["properties"]["name"].replace("Québec", "Quebec") for f in features}
    by_name = {v: k for k, v in names.items()}

    def region_of(text):
        if text in SPECIAL:
            return SPECIAL[text]
        if text in by_name:
            return by_name[text]
        m = re.search(r", ([A-Z]{2})$", text)
        if m and m.group(1) in names:
            return m.group(1)
        return None

    whole, finer = {}, {}
    for line in open(geo_path, encoding="utf-8"):
        if line.startswith("#") or "|" not in line:
            continue
        prefix, text = line.rstrip("\n").split("|", 1)
        if not prefix.startswith("1") or len(prefix) < 4:
            continue
        npa = prefix[1:4]
        region = region_of(text)
        if region is None:
            continue
        if len(prefix) == 4:
            whole[npa] = region
        else:
            finer.setdefault(npa, Counter())[region] += 1

    codes = dict(OTHER)
    for npa, count in finer.items():
        if npa not in whole and npa not in codes:
            codes[npa] = count.most_common(1)[0][0]
    for npa, region in whole.items():
        if npa not in OTHER:
            codes[npa] = region

    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "bc_area_codes.csv"), "w", encoding="utf-8") as f:
        f.write("# Generated by tools/area-codes/generate.py from libphonenumber (Apache-2.0). Don't edit.\n")
        for npa in sorted(codes):
            f.write(f"{npa},{codes[npa]}\n")
    with open(os.path.join(out_dir, "bc_regions.csv"), "w", encoding="utf-8") as f:
        f.write("# Generated by tools/area-codes/generate.py from Natural Earth (public domain). Don't edit.\n")
        for code in sorted(names):
            f.write(f"{code},{names[code]}\n")
    write_map(features, os.path.join(out_dir, "bc_map.bin"))
    print(f"{len(codes)} area codes, {len(names)} regions")


def simplify(points, tolerance):
    """Douglas-Peucker, iterative."""
    if len(points) < 4:
        return points
    keep = [False] * len(points)
    keep[0] = keep[-1] = True
    stack = [(0, len(points) - 1)]
    while stack:
        a, b = stack.pop()
        ax, ay = points[a]
        bx, by = points[b]
        dx, dy = bx - ax, by - ay
        length = math.hypot(dx, dy) or 1e-12
        best, index = -1.0, -1
        for i in range(a + 1, b):
            px, py = points[i]
            d = abs(dy * px - dx * py + bx * ay - by * ax) / length
            if d > best:
                best, index = d, i
        if best > tolerance and index > 0:
            keep[index] = True
            stack.append((a, index))
            stack.append((index, b))
    return [p for p, k in zip(points, keep) if k]


def simplify_ring(ring, tolerance):
    """A closed ring starts and ends on the same point: simplify its two halves."""
    if ring[0] == ring[-1]:
        ring = ring[:-1]
    half = len(ring) // 2
    return simplify(ring[:half + 1], tolerance)[:-1] + simplify(ring[half:] + ring[:1], tolerance)[:-1]


def ring_area(ring):
    return abs(sum(x1 * y2 - x2 * y1 for (x1, y1), (x2, y2) in zip(ring, ring[1:] + ring[:1]))) / 2


def write_map(features, path):
    """
    bc_map.bin, big-endian: int16 region count; per region: 2 ASCII bytes code, int16 centre
    lon*100, int16 centre lat*100, int16 ring count; per ring: int16 point count, then
    int16 lon*100, int16 lat*100 pairs. Longitudes east of 0 (the Aleutians) are moved west.
    """
    out = bytearray(struct.pack(">h", len(features)))
    for f in sorted(features, key=lambda f: f["properties"]["postal"]):
        p = f["properties"]
        geom = f["geometry"]
        polygons = geom["coordinates"] if geom["type"] == "MultiPolygon" else [geom["coordinates"]]
        rings = []
        for polygon in polygons:
            outer = [((x - 360 if x > 0 else x), y) for x, y in polygon[0]]
            if ring_area(outer) < 0.15:  # tiny islands vanish at this size
                continue
            ring = simplify_ring(outer, 0.12)
            if len(ring) >= 4:
                rings.append(ring)
        if not rings:  # keep at least the largest piece
            outer = max((poly[0] for poly in polygons), key=ring_area)
            rings = [simplify_ring([((x - 360 if x > 0 else x), y) for x, y in outer], 0.05)]
        lon, lat = p["longitude"], p["latitude"]
        out += p["postal"].encode("ascii") + struct.pack(">hhh", round(lon * 100), round(lat * 100), len(rings))
        for ring in rings:
            out += struct.pack(">h", len(ring))
            for x, y in ring:
                out += struct.pack(">hh", round(x * 100), round(y * 100))
    open(path, "wb").write(out)


if __name__ == "__main__":
    main(*sys.argv[1:4])
